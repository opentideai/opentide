// @layer verification — the node_dependency_lock gate (Milestone 6, Slice 6.2). A
// Result-returning, never-throwing gate that proves the committed
// `package-lock.json` shipped in the Node artifact is FROZEN-valid for that
// artifact's generated `package.json`, validated OFFLINE. It is the Node
// counterpart of the deno-source `dependency_lock` gate (verification/
// production-lock.ts): where that validates a committed `deno.lock` with `deno
// install --frozen`, this validates a committed `package-lock.json` with npm's
// offline frozen-install semantics. Like 6.1, the build only ever VALIDATES this
// lock — refreshing it is a network-allowed action OUTSIDE the build path.
//
// --- The two forks the plan flagged, resolved empirically (npm 11 / node 24) ---
//
// Fork #1 — where the committed lock comes from. The lock is a PRE-EXISTING
// input, never produced at build time: `readCommittedNodeLock(projectDir)` reads
// `<projectDir>/package-lock.json` verbatim (an adopted Node project has one;
// core/codebase/discovery.ts already maps package-lock.json → the "npm" package
// manager). Its bytes are threaded through `ExportProjectOptions.packageLock` so
// `exportProject` emits them into the deno-source export (for free manifest /
// determinism coverage) and `buildNodeFiles` passes them verbatim into the Node
// artifact — the export path itself reads no filesystem, so it stays pure and
// deterministic. A generated-from-scratch app has no committed lock, so none is
// emitted and this gate SKIPS cleanly (the COMMON path). NOTE the adopted-vs-
// generated twist: the Node artifact's `package.json` is REGENERATED by
// buildNodeFiles+generatePackageJson (framework deps pinned to exact versions), so
// it is NOT the adopted project's own package.json. A committed lock captured for
// the adopted package.json therefore generally will NOT match the generated one
// and this gate FAILS it — correctly, because that lock does not describe the
// bytes we ship. A committed lock that DOES match the generated package.json
// (produced by the deferred, network-allowed refresh action, or by an out-of-band
// `npm install --package-lock-only` over the generated package.json) validates.
//
// Fork #2 — the offline frozen check. `npm ci --dry-run --offline --ignore-scripts
// --no-audit --no-fund`, run in a tmp dir holding just the generated
// `package.json` + the committed `package-lock.json`, against an ISOLATED EMPTY
// npm cache. npm builds the ideal tree from the lock alone: on an exact match it
// needs no tarballs and no network (exit 0); on any divergence where package.json
// requires something the lock can't supply (a missing dep, a version the lock does
// not pin — the adopted-vs-generated case) npm must reconcile, which needs the
// network, so offline it exits non-zero. The gate keys on that exit code the way
// 6.1 keys on `deno install --frozen` and the Node smoke gate keys on `npm ci`.
// `--dry-run` never builds `node_modules` (fast); the isolated empty cache makes
// the verdict deterministic — a warm `~/.npm` could otherwise let a mismatch
// resolve an alternative version from cache and mask the drift. This validates the
// lock's CORRESPONDENCE to the generated package.json offline; tarball-integrity
// verification (which needs the tarballs, hence the network) is left to the Node
// smoke gate's real `npm ci`.
//
// Because the lock ships as an ExportFile (emitted before the manifest), the
// manifest gate hashes it and the determinism gate byte-covers it for FREE — no
// change to those gates.
import { readFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { type ExportFile, fileBytes } from "../core/export.ts";
import { writeExportFiles } from "../core/build.ts";
import type { Result } from "../core/types.ts";

// The committed lockfile's + manifest's fixed paths in the Node artifact.
export const PACKAGE_LOCKFILE_PATH = "package-lock.json";
const PACKAGE_JSON_PATH = "package.json";

// Semantic error codes (no magic strings). INVALID is the pure pre-check failure
// (a malformed lock); the umbrella EXPORT_NODE_DEPENDENCY_LOCK_FAILED covers the
// frozen check (a stale/mismatched lock or a spawn failure) — mirroring the
// one-umbrella-code convention of the deno-source gate.
export const NODE_DEPENDENCY_LOCK_INVALID = "NODE_DEPENDENCY_LOCK_INVALID";
export const EXPORT_NODE_DEPENDENCY_LOCK_FAILED =
  "EXPORT_NODE_DEPENDENCY_LOCK_FAILED";

// The skip reason for a Node artifact that carries no committed package-lock.json —
// a generated app that never had one. Exported so tests can assert the skip
// without a magic string.
export const NO_COMMITTED_NODE_LOCK_DETAIL =
  "no committed package-lock.json to validate";

// The gate's own tmp dir under <projectDir>/dist, distinct from every smoke dir
// and from the deno-source lock gate's dir (so the two never corrupt each other).
const NODE_LOCK_TMP_DIR = ".tmp-node-dep-lock";

// The isolated, empty npm cache dir (under the tmp dir) the frozen check runs
// against. Empty by construction so a match resolves purely from the lock and a
// mismatch cannot borrow an alternative version from a warm cache — the verdict is
// deterministic and offline.
const NPM_CACHE_DIR = ".npm-cache";

// The offline frozen-validation command. `ci` installs strictly from the lock;
// `--dry-run` validates the lock ↔ package.json correspondence WITHOUT building
// node_modules (fast, and needs no tarballs on a match); `--offline` forbids the
// network so a mismatch that would need reconciliation exits non-zero rather than
// silently resolving online. --ignore-scripts/--no-audit/--no-fund keep it quiet
// and side-effect-free.
const FROZEN_CHECK_ARGS = [
  "ci",
  "--dry-run",
  "--offline",
  "--ignore-scripts",
  "--no-audit",
  "--no-fund",
] as const;

const NPM_BIN = "npm";

// The gate's typed outcome. A discriminated union so the orchestrator can map a
// clean SKIP (`verified: false`, no committed lock) to a skipped GateOutcome and a
// real validation (`verified: true`) to a passed one — both are `ok: true`
// Results; only a malformed/stale lock is an `ok: false` failure.
export type NodeDependencyLockVerification =
  | { verified: true; lockfile: string; packageCount: number }
  | { verified: false; reason: string };

function errorMessage(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}

// Read the committed `<projectDir>/package-lock.json` verbatim, or undefined when
// the project has none (a generated app) or it can't be read. Never throws — a
// missing/unreadable lock simply means "nothing to ship", and the gate then skips.
// This is the ONLY filesystem read in the sourcing path; the export itself stays
// pure by receiving the bytes via ExportProjectOptions.packageLock.
export function readCommittedNodeLock(projectDir: string): string | undefined {
  try {
    return readFileSync(join(projectDir, PACKAGE_LOCKFILE_PATH), "utf-8");
  } catch {
    return undefined;
  }
}

// Count the packages a lock pins, for the passing gate's detail. lockfileVersion 2+
// keys them under `packages` (the root "" entry excluded); falls back to the
// legacy `dependencies` map. Assumes `parsed` already validated as an object.
function countLockedPackages(parsed: Record<string, unknown>): number {
  const packages = parsed.packages;
  if (packages && typeof packages === "object") {
    return Object.keys(packages).filter((k) => k !== "").length;
  }
  const dependencies = parsed.dependencies;
  return dependencies && typeof dependencies === "object"
    ? Object.keys(dependencies).length
    : 0;
}

// Pure well-formedness pre-check on the committed lock BEFORE spawning anything: it
// must parse as a JSON object carrying a numeric `lockfileVersion` (every npm
// lockfile has one since npm 5). Returns the parsed object on success, or an
// INVALID failure message. A garbage lock fails here (fast, offline) rather than as
// an opaque frozen exit.
function parseLock(text: string): Result<Record<string, unknown>> {
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch (err) {
    return {
      ok: false,
      error: {
        code: NODE_DEPENDENCY_LOCK_INVALID,
        message: `${PACKAGE_LOCKFILE_PATH} is not valid JSON: ${
          errorMessage(err)
        }`,
      },
    };
  }
  if (typeof parsed !== "object" || parsed === null) {
    return {
      ok: false,
      error: {
        code: NODE_DEPENDENCY_LOCK_INVALID,
        message: `${PACKAGE_LOCKFILE_PATH} must be a JSON object.`,
      },
    };
  }
  const record = parsed as Record<string, unknown>;
  if (typeof record.lockfileVersion !== "number") {
    return {
      ok: false,
      error: {
        code: NODE_DEPENDENCY_LOCK_INVALID,
        message:
          `${PACKAGE_LOCKFILE_PATH} is missing a numeric "lockfileVersion".`,
      },
    };
  }
  return { ok: true, data: record };
}

function lockFailure(
  message: string,
): Result<NodeDependencyLockVerification> {
  return {
    ok: false,
    error: { code: EXPORT_NODE_DEPENDENCY_LOCK_FAILED, message },
  };
}

/**
 * Gate: the committed `package-lock.json` shipped in the Node artifact `files` is
 * frozen-valid for its generated `package.json`, validated offline. Never throws.
 *
 * - No `package-lock.json` in the Node artifact → `ok: true` with
 *   `verified: false` (a clean SKIP; the orchestrator renders it as a skipped
 *   gate, not a failure).
 * - Present but malformed (unparseable / not an object / no `lockfileVersion`) →
 *   `NODE_DEPENDENCY_LOCK_INVALID` (a fast, offline, pure pre-check).
 * - Present and well-formed → writes the generated `package.json` + the committed
 *   `package-lock.json` to a tmp dir and runs the offline `npm ci --dry-run`
 *   frozen check against an isolated empty cache; exit 0 → `verified: true`; any
 *   non-zero exit or a spawn failure → `EXPORT_NODE_DEPENDENCY_LOCK_FAILED` (a
 *   stale / mismatched lock, e.g. one captured for a different package.json).
 *
 * `files` must be the NODE artifact (from buildNodeFiles) so it carries the
 * generated `package.json`; `projectDir` only locates the (self-cleaning) tmp dir.
 * The frozen check needs only those two files, so this gate re-reads nothing from
 * the project.
 */
export async function verifyNodeDependencyLock(
  files: ExportFile[],
  projectDir: string,
): Promise<Result<NodeDependencyLockVerification>> {
  const lock = files.find((f) => f.path === PACKAGE_LOCKFILE_PATH);
  if (!lock) {
    return {
      ok: true,
      data: { verified: false, reason: NO_COMMITTED_NODE_LOCK_DETAIL },
    };
  }

  const parsed = parseLock(new TextDecoder().decode(fileBytes(lock)));
  if (!parsed.ok) return parsed;
  const packageCount = countLockedPackages(parsed.data);

  const packageJson = files.find((f) => f.path === PACKAGE_JSON_PATH);
  if (!packageJson) {
    // Defensive: a Node artifact always carries a generated package.json. Without
    // it there is nothing to validate the lock against.
    return lockFailure(
      `${PACKAGE_JSON_PATH} missing from the Node artifact; cannot validate ${PACKAGE_LOCKFILE_PATH}.`,
    );
  }

  const tmpDir = join(projectDir, "dist", NODE_LOCK_TMP_DIR);
  try {
    rmSync(tmpDir, { recursive: true, force: true });
    // `npm ci --dry-run` reads only package.json + package-lock.json, so writing
    // just those two keeps the gate light (no transpiled sources needed) — the
    // rest of the Node artifact is irrelevant to the lock ↔ package.json check.
    writeExportFiles(tmpDir, [packageJson, lock]);

    let output: Deno.CommandOutput;
    try {
      output = await new Deno.Command(NPM_BIN, {
        args: [...FROZEN_CHECK_ARGS],
        cwd: tmpDir,
        stdout: "piped",
        stderr: "piped",
        env: {
          // Isolated empty cache: a match resolves purely from the lock; a
          // mismatch cannot borrow an alternative version from a warm cache.
          npm_config_cache: join(tmpDir, NPM_CACHE_DIR),
          npm_config_update_notifier: "false",
        },
      }).output();
    } catch (err) {
      return lockFailure(
        `Node dependency lock check could not run: ${errorMessage(err)}`,
      );
    }

    if (!output.success) {
      const stderr = new TextDecoder().decode(output.stderr).trim();
      return lockFailure(
        `Committed ${PACKAGE_LOCKFILE_PATH} is not frozen-valid for the exported Node app's ${PACKAGE_JSON_PATH} (exit code ${output.code}).${
          stderr ? `\n${stderr}` : ""
        }`,
      );
    }

    return {
      ok: true,
      data: {
        verified: true,
        lockfile: PACKAGE_LOCKFILE_PATH,
        packageCount,
      },
    };
  } finally {
    rmSync(tmpDir, { recursive: true, force: true });
  }
}
