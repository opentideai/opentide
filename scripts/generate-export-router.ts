// Regenerate core/export-router.ts from core/route-matcher.ts.
//
// The app export ships its own copy of the route matcher — a standalone source tree
// cannot import the kernel — and core/export-router_test.ts holds that copy to the
// original verbatim. When the matcher changes, that gate fails; run
//
//     deno task router:generate
//
// to bring the emitted copy back in line, then re-read the diff. This is the only way
// the emitted copy should ever be edited: hand-editing the escaped template literal is
// how the two halves drift, and every backslash in the matcher's regexes is doubled in
// there.

const MATCHER = new URL("../core/route-matcher.ts", import.meta.url);
const TARGET = new URL("../core/export-router.ts", import.meta.url);

export const MATCHER_MARKER = "// --- The matcher ---";

// What the emitted file says about itself. The in-repo module's header talks about both
// hosts and about generation; the copy that ships with a user's app talks about the app.
const EMITTED_HEADER =
  `// The exported app's route matcher, on URLPattern — a web standard, global in Deno
// and in Node 24+. This shell used to be a Hono app; this file is what replaced its
// routing, and every behaviour below was MEASURED against Hono 4 rather than assumed.
// core/export-router_test.ts is the gate: it loads THIS emitted file,
// registers the same table with real Hono, and compares answers over the routes the
// field uses, a precedence corpus and a seeded fuzz.`;

const MODULE_HEADER =
  `// @layer core — the emitted source of the app export's route matcher.
//
// GENERATED by scripts/generate-export-router.ts from core/route-matcher.ts.
// Do not hand-edit: edit the kernel's matcher and run \`deno task router:generate\`.
// core/export-router_test.ts fails if the two drift.
//
// Emitted as its own file, \`router.ts\`, rather than inlined into main.ts for one reason
// that matters: the differential gate can import the artifact that actually ships and
// compare it against Hono without booting PGlite. One copy, gated against the real thing.

export const ROUTER_PATH = "router.ts";`;

/** The shared half of core/route-matcher.ts: everything below the marker. */
export function inRepoMatcherSource(source: string): string {
  const start = source.indexOf(MATCHER_MARKER);
  if (start === -1) {
    throw new Error(`core/route-matcher.ts has no "${MATCHER_MARKER}"`);
  }
  const body = source.slice(start + MATCHER_MARKER.length);
  // The marker's own trailing dashes are part of the line, not of the body.
  return body.slice(body.indexOf("\n") + 1).trim();
}

// Escape for a TS template literal: backslashes, backticks, and `${`.
function escapeTemplate(text: string): string {
  return text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(
    /\$\{/g,
    "\\${",
  );
}

if (import.meta.main) {
  const matcher = inRepoMatcherSource(Deno.readTextFileSync(MATCHER));
  const emitted = `${EMITTED_HEADER}\n\n${matcher}\n`;

  Deno.writeTextFileSync(
    TARGET,
    `${MODULE_HEADER}

export function generateRouterRuntimeSource(): string {
  return \`${escapeTemplate(emitted)}\`;
}
`,
  );

  const fmt = new Deno.Command(Deno.execPath(), {
    args: ["fmt", "--quiet", TARGET.pathname],
  }).outputSync();
  if (!fmt.success) {
    throw new Error("deno fmt failed on the generated router module");
  }

  console.log(`Wrote ${TARGET.pathname}`);
}
