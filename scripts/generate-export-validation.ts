// Regenerate core/export-validation.ts from core/route-validation.ts.
//
// The app export ships its own copy of the request-time validation — a standalone source
// tree cannot import the kernel — and core/export-validation_test.ts holds that copy to
// the original verbatim. When the shared half changes, that gate fails; run
//
//     deno task validation:generate
//
// to bring the emitted copy back in line, then re-read the diff. This is the only way the
// emitted copy should ever be edited: hand-editing the escaped template literal is how
// the two halves drift.
//
// What travels is ONLY the half below the marker. deriveRouteSchemas stays in the kernel
// because the export never sees a RouteSchema — its validators were compiled to source at
// export time and the shipped app just runs them.

const VALIDATION = new URL("../core/route-validation.ts", import.meta.url);
const TARGET = new URL("../core/export-validation.ts", import.meta.url);

export const VALIDATION_MARKER =
  "// --- The shared request-time validation ---";

// What the emitted file says about itself. The in-repo module's header talks about both
// hosts and about generation; the copy that ships with a user's app talks about the app.
const EMITTED_HEADER =
  `// The exported app's request validation: the 400 a request earns when it violates the
// route's declared schema.
//
// The validator FUNCTIONS live in validators.ts, compiled to source at export time by the
// same ajv the live preview runs, so they produce the same errors down to the message
// strings. This file is what runs them, and it is the preview's own code verbatim —
// core/preview-export-parity_test.ts is the gate that keeps the two hosts answering a bad
// request identically.`;

const MODULE_HEADER =
  `// @layer core — the emitted source of the app export's request validation.
//
// GENERATED by scripts/generate-export-validation.ts from core/route-validation.ts.
// Do not hand-edit: edit the kernel's validation and run \`deno task validation:generate\`.
// core/export-validation_test.ts fails if the two drift.
//
// Emitted as its own file, \`validation.ts\`, rather than inlined into main.ts for the same
// reason \`router.ts\` is: the gate can import the artifact that actually ships and drive it
// without booting PGlite. Always emitted, even when no route declares a schema — the
// shell references it unconditionally, and validators.ts is the conditional half.

export const VALIDATION_PATH = "validation.ts";`;

/** The shared half of core/route-validation.ts: everything below the marker. */
export function inRepoValidationSource(source: string): string {
  const start = source.indexOf(VALIDATION_MARKER);
  if (start === -1) {
    throw new Error(`core/route-validation.ts has no "${VALIDATION_MARKER}"`);
  }
  const body = source.slice(start + VALIDATION_MARKER.length);
  // The marker's own trailing dashes are part of the line, not of the body.
  return body.slice(body.indexOf("\n") + 1).trim();
}

// Escape for a TS template literal: backslashes, backticks, and `${`.
function escapeTemplate(text: string): string {
  return text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(
    /\$\{/g,
    "\\${",
  );
}

if (import.meta.main) {
  const validation = inRepoValidationSource(Deno.readTextFileSync(VALIDATION));
  const emitted = `${EMITTED_HEADER}\n\n${validation}\n`;

  Deno.writeTextFileSync(
    TARGET,
    `${MODULE_HEADER}

export function generateValidationRuntimeSource(): string {
  return \`${escapeTemplate(emitted)}\`;
}
`,
  );

  const fmt = new Deno.Command(Deno.execPath(), {
    args: ["fmt", "--quiet", TARGET.pathname],
  }).outputSync();
  if (!fmt.success) {
    throw new Error("deno fmt failed on the generated validation module");
  }

  console.log(`Wrote ${TARGET.pathname}`);
}
