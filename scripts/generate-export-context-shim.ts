// Regenerate core/export-context-shim.ts from core/handler-abi.ts.
//
// The app export ships its own copy of the legacy-context shim — a standalone source
// tree cannot import the kernel — and core/export-context-shim_test.ts holds that copy
// to the original verbatim. When the kernel's shim changes, that gate fails; run
//
//     deno task shim:generate
//
// to bring the emitted copy back in line, then re-read the diff. This is the only way
// the emitted copy should ever be edited: hand-editing the escaped template literal is
// how the two halves drift.

import { ROUTE_NOT_FOUND_CODE } from "../core/config.ts";

const HANDLER_ABI = new URL("../core/handler-abi.ts", import.meta.url);
const TARGET = new URL("../core/export-context-shim.ts", import.meta.url);

const CONSTANTS_MARKER = "/** Hono's own constant";
const DETECTION_MARKER = "// --- Detection ---";
const SHIM_MARKER = "// --- The legacy compatibility shim ---";

const EMITTED_HEADER =
  `// The legacy handler compatibility shim, emitted into the app export.
//
// Handlers are \`(req: Request, ctx: HandlerContext) => Response\`. Before that they
// took a Hono \`Context\`, and stored sources were never migrated — the ABI is derived
// from the source and the legacy ones are wrapped. Inside the kernel that wrapping
// is core/handler-abi.ts; here it has to ship with the app, because the exported
// shell no longer imports Hono and so has no Context to hand over.
//
// This file is a copy of core/handler-abi.ts's shim half. The copy is deliberate —
// an export is a standalone source tree and cannot import the kernel — and it is held
// to the original verbatim by core/export-context-shim_test.ts. Do not edit it here;
// edit core/handler-abi.ts and run \`deno task shim:generate\`.
//
// Two quirks below look like bugs and are not: \`c.text()\` emits
// \`text/plain;charset=UTF-8\` (no space) when nothing else has been set on the
// context and \`text/plain; charset=UTF-8\` (with a space) once it has, because the
// first case hands the string straight to the \`Response\` constructor; and \`c.body()\`
// never sets content-type itself, leaving it to the constructor or to whatever
// \`c.header()\` already put there.

import type { HandlerContext } from "./deps.ts";

type HandlerFn = (
  req: Request,
  ctx: HandlerContext,
) => Response | Promise<Response>;

// The kernel's shim imports this from core/config.ts, which an export cannot reach, so
// the value read at generation time is inlined under the SAME identifier — that keeps
// the shim text below byte-identical to the kernel's, which is what the gate checks.
const ROUTE_NOT_FOUND_CODE = ${JSON.stringify(ROUTE_NOT_FOUND_CODE)};
`;

const EMITTED_TRAILER =
  `/** The name legacy handler sources annotate their parameter with. */
export type Context = LegacyContext;
`;

const MODULE_HEADER =
  `// @layer core — the emitted source of the app export's legacy-context shim.
//
// GENERATED by scripts/generate-export-context-shim.ts from core/handler-abi.ts.
// Do not hand-edit: edit the kernel's shim and run \`deno task shim:generate\`.
// core/export-context-shim_test.ts fails if the two drift.

export const CONTEXT_SHIM_PATH = "context-shim.ts";
`;

function section(source: string, from: string, to?: string): string {
  const start = source.indexOf(from);
  if (start === -1) throw new Error(`core/handler-abi.ts has no "${from}"`);
  const end = to === undefined ? source.length : source.indexOf(to, start);
  if (end === -1) throw new Error(`core/handler-abi.ts has no "${to}"`);
  return source.slice(start, end).trim();
}

// Escape for a TS template literal: backslashes, backticks, and `${`.
function escapeTemplate(text: string): string {
  return text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(
    /\$\{/g,
    "\\${",
  );
}

const source = Deno.readTextFileSync(HANDLER_ABI);
const constants = section(source, CONSTANTS_MARKER, DETECTION_MARKER);
const shim = section(source, SHIM_MARKER)
  .slice(SHIM_MARKER.length)
  .trim();

const emitted = [EMITTED_HEADER, constants, shim, EMITTED_TRAILER].join("\n\n");

Deno.writeTextFileSync(
  TARGET,
  `${MODULE_HEADER}
export function generateContextShimRuntimeSource(): string {
  return \`${escapeTemplate(emitted)}\`;
}
`,
);

const fmt = new Deno.Command(Deno.execPath(), {
  args: ["fmt", "--quiet", TARGET.pathname],
}).outputSync();
if (!fmt.success) {
  throw new Error("deno fmt failed on the generated shim module");
}

console.log(`Wrote ${TARGET.pathname}`);
